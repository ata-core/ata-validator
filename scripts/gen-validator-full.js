'use strict';
// Writes lib/validator-full.js, the Validator of the full 2.0 entries
// (index.v2.browser.mjs, index.v2.edge.mjs): lib/validator-small.js, the
// plugin's core, with each block between its core markers replaced as below.
// The full entries take every schema without a feature registered for it, so
// they wire the schema-decided groups in from their modules (lib/formats.js,
// lib/unique-items.js, lib/branch-collapse.js, lib/draft7.js, lib/defaults.js)
// and carry none of the registration, the questions asked of a schema's text
// (lib/gates.js) or featuresFor()'s recorder. Generated rather than built with
// a flag, so a page bundler that knows no flag drops nothing it should keep.
// tests/test_validator_full_sync.js fails when the copy has drifted.
const fs = require('fs');
const path = require('path');

const FULL = {
  setup: [
    "const need = (name, as) => features[name] || missing(name + ', Validator.use(' + (as || name) + ')');",
  ],
  features: [
    "const features = { errorMessage: null, metaschemas: null, coerceTypes: null, removeAdditional: null, codegen: null, richErrors: null, verbose: null };",
  ],
  regroup: [],
  gates: ["    if (map !== null) require('./schema-order').registerDocuments(schemaObj, map);"],
  stop: [],
  rich: ["    if (r !== undefined && !f) need('richErrors');"],
  use: [],
  exports: ['module.exports = { Validator };'],
};

// lib/engine-full.js: lib/engine-small.js reading the groups from their
// modules where the core reads them from what was registered (lib/groups.js).
const ENGINE = [
  ["const { G, refuse, builtinFormat } = require('./groups')\n", "const { _deq: eq, duplicatePair } = require('./unique-items')\nlet _collapse = null\nconst collapse = (kw, br, pp, sp, o) => (_collapse || (_collapse = require('./branch-collapse')._collapse))(kw, br, pp, sp, o)\nlet formatTable = null\n"],
  ['  // Enum and const equality, as the Validator set it (lib/groups.js).\n  const eq = G.eq\n', ''],
  ['      const name = s.format\n', "      const name = s.format; const table = formatTable || (formatTable = require('./formats').formatChecks())\n"],
  [": builtinFormat(name)\n", ": has(table, name) && typeof table[name] === 'function' ? table[name] : null\n"],
  ["      const duplicatePair = G.dup || refuse('uniqueItems')\n", ''],
  ["      const collapse = G.collapse || refuse('branchCollapse')\n", ''],
];
function renderEngine () {
  let src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'engine-small.js'), 'utf8');
  for (const [a, b] of ENGINE) {
    if (src.split(a).length !== 2) throw new Error('gen-validator-full: lib/engine-small.js no longer holds, once, ' + JSON.stringify(a.slice(0, 60)));
    src = src.replace(a, b);
  }
  if (/\bG\.|refuse|builtinFormat|groups'/.test(src.replace(/^[ \t]*\/\/[^\n]*\n/gm, ''))) throw new Error('gen-validator-full: the full engine still reads lib/groups.js');
  return "'use strict'\n// Generated by scripts/gen-validator-full.js from lib/engine-small.js. Do not edit.\n" + src.replace(/^'use strict'\n/, '').replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n');
}

// Lines of lib/validator-small.js outside the core blocks that differ: the
// full engine, draft7 and defaults required where they are used, and the
// `definitions` rename read as it is only on the core, where it saves the
// draft7 group (a full entry carries draft7 anyway).
const SUBS = [
  ["const { createSmall } = require('./engine-small');", "const { createSmall } = require('./engine-full');"],
  ["const { needsNormalization, scan, DEFINITIONS } = require('./schema-scan');", "const { needsNormalization } = require('./schema-scan');"],
  ['  const k = (inherit || 0) + (shown ? 8 : 0), c = kept.get(s);', '  const c = kept.get(s);'],
  ['    let schemaObj = normalize(raw, 0, !!o.verbose);', '    let schemaObj = normalize(raw, 0);'],
  ["  if (c && c[0] === k) return need('draft7') && c[1];", '  if (c && c[0] === inherit) return c[1];'],
  ['  kept.set(s, [k, copy]);', '  kept.set(s, [inherit, copy]);'],
  ['  if (code === 1 && !shown && scan(s) === DEFINITIONS) return s;\n', ''],
  ["  const d = need('draft7');", "  const d = require('./draft7');"],
  ["need('draft7').stripFormatAssertions", "require('./draft7').stripFormatAssertions"],
  ["need('defaults').buildDefaultsApplier", "require('./defaults').buildDefaultsApplier"],
];

function render () {
  let src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'validator-small.js'), 'utf8');
  for (const [a, b] of SUBS) {
    if (src.split(a).length !== 2) throw new Error('gen-validator-full: lib/validator-small.js no longer holds, once, ' + JSON.stringify(a.slice(0, 60)));
    src = src.replace(a, b);
  }
  for (const [name, lines] of Object.entries(FULL)) {
    const re = new RegExp('^// ---- core: begin ' + name + ' ----\\n[^]*?^// ---- core: end ' + name + ' ----\\n', 'm');
    if (!re.test(src)) throw new Error('gen-validator-full: lib/validator-small.js has no core block ' + name);
    src = src.replace(re, lines.length ? lines.join('\n') + '\n' : '');
  }
  if (/---- core:/.test(src)) throw new Error('gen-validator-full: lib/validator-small.js has a core block the generator does not know');
  if (/PROBE|gates\b|regroup|\bG\b|engine-small/.test(src.replace(/^[ \t]*\/\/[^\n]*\n/gm, ''))) throw new Error('gen-validator-full: the full Validator still reads the core\'s registration');
  return "'use strict';\n// Generated by scripts/gen-validator-full.js from lib/validator-small.js. Do not edit.\n" +
    src.replace(/^'use strict';\n/, '').replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n');
}

const file = path.join(__dirname, '..', 'lib', 'validator-full.js');
const engineFile = path.join(__dirname, '..', 'lib', 'engine-full.js');
if (require.main === module) { fs.writeFileSync(file, render()); fs.writeFileSync(engineFile, renderEngine()); }
module.exports = { render, file, renderEngine, engineFile };
