'use strict';
// Writes lib/engine-shared.js: the code the interpreted engines share (the
// resource index, reference resolution, pattern matchers), taken from the
// lines of lib/interpreter-core.js between its engine-shared markers, for the
// small engine (lib/engine-small.js) to require. The interpreter keeps the
// code inline because a module boundary cost a browser bundle 173 bytes
// gzipped. tests/test_engine_shared_sync.js fails when the copy has drifted.
const fs = require('fs');
const path = require('path');

const BEGIN = '// ---- engine-shared: begin ----\n';
const END = '// ---- engine-shared: end ----\n';
const EXPORTS = ['indexSchemas', 'resolveRef', 'splitFragment', 'resolveUri', 'FALLBACK_BASE', 'plainLinear', 'compilePattern'];

function render () {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'interpreter-core.js'), 'utf8');
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('lib/interpreter-core.js has no engine-shared markers');
  return "'use strict';\n// Generated by scripts/gen-engine-shared.js from lib/interpreter-core.js. Do not edit.\n\n" +
    // Whole-line comments stay in lib/interpreter-core.js, where the code is read.
    src.slice(a + BEGIN.length, b).replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n') + '\nmodule.exports = { ' + EXPORTS.join(', ') + ' };\n';
}

const file = path.join(__dirname, '..', 'lib', 'engine-shared.js');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
