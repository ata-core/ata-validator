'use strict';
// Writes lib/engine-shared.js: the code the interpreted engines share (the
// resource index, reference resolution, pattern matchers), taken from the
// lines of lib/interpreter-core.js between its engine-shared markers, for the
// small engine (lib/engine-small.js) to require. The interpreter keeps the
// code inline because a module boundary cost a browser bundle 173 bytes
// gzipped. tests/test_engine_shared_sync.js fails when the copy has drifted.
//
// Also writes lib/engine-shared-core.js, the same lines for the plugin's core
// (lib/validator-small.js, lib/engine-small.js), where the linear pattern
// engine (lib/safe-regex.js) is the patterns feature and not a require:
// compilePattern takes the engine the Validator registered, and refuses a
// pattern that needs it when none was (`ata2: patterns`), before the
// fallback to the platform RegExp could take it. The test that sends a
// pattern to the platform RegExp is the source's own expression, exported as
// onPlatform, so featuresFor() (lib/gates.js) asks the question the engine
// answers. The full entries' engine (lib/engine-full.js) and the verdict core
// read lib/engine-shared.js, which keeps the require.
const fs = require('fs');
const path = require('path');

const BEGIN = '// ---- engine-shared: begin ----\n';
const END = '// ---- engine-shared: end ----\n';
const EXPORTS = ['indexSchemas', 'resolveRef', 'splitFragment', 'resolveUri', 'FALLBACK_BASE', 'plainLinear', 'compilePattern', 'walkPointer'];

const ENGINE = "let _safeRe = null;\nconst compileSafe = (src) => (_safeRe || (_safeRe = require('./safe-regex'))).compileSafe(src);\n";
const HEAD = 'function compilePattern(src) {\n  let re;\n';
const ROUTE = /^  if \((.+)\) \{\n/m;
const CALL = '    try {\n      re = compileSafe(src);\n';
// The rethrow for the shared error runtime's stub engine (lib/error-runtime.js),
// which the core never loads: there a missing engine is the refusal above.
const STUB = "      if (e && typeof e.message === 'string' && e.message.includes('built without the pattern engine')) throw e;\n";

// The 1.x Validator's patternFallback hook (lib/pattern-fallback.js) is a
// parameter of the interpreter's compilePattern. The 2.0 engines take the
// option as a feature that wraps their compile instead
// (lib/features/patternFallback.js), so their copies are written without it.
const HOOKED = [
  ['function compilePattern(src, hook) {\n', 'function compilePattern(src) {\n'],
  ['    try {\n      return compileSafe(src);\n', '    try {\n      re = compileSafe(src);\n'],
  ['  return hook ? hook(src, re) : re;\n', '  return re;\n'],
];

function block () {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'interpreter-core.js'), 'utf8');
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('lib/interpreter-core.js has no engine-shared markers');
  let s = src.slice(a + BEGIN.length, b);
  for (const [from, to] of HOOKED) {
    if (s.split(from).length !== 2) throw new Error('gen-engine-shared: lib/interpreter-core.js no longer holds, once, ' + JSON.stringify(from));
    s = s.replace(from, () => to);
  }
  return s;
}

// Whole-line comments stay in lib/interpreter-core.js, where the code is read.
const strip = (s) => s.replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n');
const once = (s, a, what) => { if (s.split(a).length !== 2) throw new Error('gen-engine-shared: lib/interpreter-core.js no longer holds, once, ' + what); };

function render () {
  return "'use strict';\n// Generated by scripts/gen-engine-shared.js from lib/interpreter-core.js. Do not edit.\n\n" +
    strip(block()) + '\nmodule.exports = { ' + EXPORTS.join(', ') + ' };\n';
}

function renderCore () {
  let s = strip(block());
  once(s, ENGINE, 'the linear engine require');
  once(s, HEAD, 'the head of compilePattern');
  once(s, CALL, 'the linear engine call in compilePattern');
  once(s, STUB, 'the rethrow of the stub engine\'s error');
  const at = s.indexOf(HEAD) + HEAD.length;
  const m = ROUTE.exec(s.slice(at));
  if (m === null || m.index !== 0) throw new Error('gen-engine-shared: compilePattern no longer opens with its test for the platform RegExp');
  s = s.slice(0, at) + '  if (onPlatform(src)) {\n' + s.slice(at + m[0].length);
  s = s.replace(HEAD, () => 'function compilePattern(src, safe) {\n  let re;\n');
  s = s.replace(STUB, '');
  s = s.replace(CALL, () => "    if (!safe) refuse('patterns');\n    try {\n      re = safe.compileSafe(src);\n");
  s = s.replace(ENGINE, () => "const { refuse } = require('./groups');\nconst onPlatform = (src) => " + m[1] + ';\n');
  if (/safe-regex|(?<!\.)compileSafe\(/.test(s)) throw new Error('gen-engine-shared: the core copy still reaches lib/safe-regex.js');
  return "'use strict';\n// Generated by scripts/gen-engine-shared.js from lib/interpreter-core.js. Do not edit.\n\n" +
    s + '\nmodule.exports = { ' + EXPORTS.concat('onPlatform').join(', ') + ' };\n';
}

const file = path.join(__dirname, '..', 'lib', 'engine-shared.js');
const coreFile = path.join(__dirname, '..', 'lib', 'engine-shared-core.js');
if (require.main === module) { fs.writeFileSync(file, render()); fs.writeFileSync(coreFile, renderCore()); }
module.exports = { render, file, renderCore, coreFile };
