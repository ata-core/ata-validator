'use strict';
// Writes lib/ir/emit-deps.mjs: what the module writer (lib/ir/emit.mjs) takes
// from two CommonJS files, as their text. The pattern unrolling of
// lib/js-compiler.js and the format hints of lib/suggestions.js. The writer
// then loads in a browser without the code generator, without reading files
// and without evaluating strings. The hints are written into modules by their
// source text, which a copy keeps.
// tests/test_ir_emit_deps_sync.js fails when the copy and the sources differ.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

const lib = (f) => fs.readFileSync(path.join(__dirname, '..', 'lib', f), 'utf8');
function block (src, start, end, what) {
  const a = src.indexOf(start);
  const b = a < 0 ? -1 : src.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error('gen-ir-emit-deps: ' + what + ' not found');
  return src.slice(a, b + end.length);
}

function render () {
  const jsc = lib('js-compiler.js');
  return `// Generated by scripts/gen-ir-emit-deps.js from lib/js-compiler.js and lib/suggestions.js. Do not edit.
${block(jsc, 'const FIXED_LITERAL = ', '\n', 'FIXED_LITERAL').trim()}
${take('js-compiler.js', ['compilePatternInline', 'fixedSequenceInline', 'charClassToCheck'])}
${block(lib('suggestions.js'), 'const FORMAT_HINTS = {', '\n};', 'FORMAT_HINTS')}
export { compilePatternInline, FORMAT_HINTS };
`;
}

const file = path.join(__dirname, '..', 'lib', 'ir', 'emit-deps.mjs');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
