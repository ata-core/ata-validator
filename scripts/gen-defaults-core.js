'use strict';
// Writes lib/defaults-core.js: lib/defaults.js for the defaults feature of the
// plugin's core (lib/features/defaults.js), with patternProperties keys
// matched without a require of the linear pattern engine (lib/safe-regex.js).
// On the core that engine is the patterns feature: the Validator hands the one
// it registered to buildDefaultsApplier. A key the platform RegExp takes, by
// the test compilePattern makes (onPlatform, lib/engine-shared-core.js), is
// matched there, as validation on the core matches it; any other is matched
// as lib/defaults.js matches it, on the engine registered, and with none
// registered the schema is refused (`ata2: patterns`) rather than given a
// backtracking RegExp. lib/defaults.js, which the full entries and 1.x carry,
// keeps its require. tests/test_defaults_core_sync.js fails when the copy has
// drifted.
const fs = require('fs');
const path = require('path');

// The tail of lib/defaults.js this replaces, without its comments.
const TAIL = `const PROP_ESCAPE = /\\\\[pP]\\{/;
function safeKeyMatcher(src) {
  if (!PROP_ESCAPE.test(src)) {
    try {
      const safe = require("./safe-regex");
      if (safe.patternIsSafe(src)) return safe.compileSafe(src);
    } catch {}
  }
  return keyPattern(src);
}

module.exports = {
  buildDefaultsApplier: (schema, match = safeKeyMatcher) => buildDefaultsApplier(schema, match),
  setOwn, localRef, resourceRoots, refTarget, reachGraph, reachesDefault, safeKeyMatcher, MAX_DEPTH, EMBED,
};
`;

const CORE = `const { onPlatform } = require("./engine-shared-core");
const { refuse } = require("./groups");
function safeKeyMatcher(src, safe) {
  if (onPlatform(src)) return keyPattern(src);
  if (!safe) refuse("patterns");
  try {
    return safe.compileSafe(src);
  } catch {}
  return keyPattern(src);
}

module.exports = {
  buildDefaultsApplier: (schema, safe, match = (src) => safeKeyMatcher(src, safe)) => buildDefaultsApplier(schema, match),
  setOwn, localRef, resourceRoots, refTarget, reachGraph, reachesDefault, safeKeyMatcher, MAX_DEPTH, EMBED,
};
`;

function render () {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'defaults.js'), 'utf8')
    // Whole-line comments stay in lib/defaults.js, where the code is read.
    .replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n');
  if (!src.endsWith(TAIL)) throw new Error('gen-defaults-core: the key matcher or the exports of lib/defaults.js have changed; update scripts/gen-defaults-core.js');
  const out = src.slice(0, -TAIL.length) + CORE;
  if (/safe-regex/.test(out)) throw new Error('gen-defaults-core: the copy still reaches lib/safe-regex.js');
  return out.replace(/^(['"])use strict\1;\n/, "'use strict';\n// Generated by scripts/gen-defaults-core.js from lib/defaults.js. Do not edit.\n");
}

const file = path.join(__dirname, '..', 'lib', 'defaults-core.js');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
