'use strict';
// Writes lib/kernels/custom.mjs: from lib/interpreter-core.js, the order the
// custom keywords of one node run in (orderCustom) and the type bits their
// `type` is matched with (typeBit, dataBits, the T_ constants), as their text.
// The IR's closure backend runs custom keywords with them, as the interpreted
// engine does, without loading that engine.
// tests/test_kernels_custom_sync.js fails when the copy and the source differ.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

function render () {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'interpreter-core.js'), 'utf8');
  const consts = src.match(/^const T_[A-Z]+ = \d+;$/gm);
  if (!consts || consts.length < 8) throw new Error('gen-kernels-custom: the T_ constants were not found in lib/interpreter-core.js');
  return `// Generated by scripts/gen-kernels-custom.js from lib/interpreter-core.js. Do not edit.
${consts.join('\n')}
// The value a context-reading keyword is given, read from the document being
// validated; the interpreter keeps that document on itself (ctxInterp).
let ctxInterp = null;
${take('interpreter-core.js', ['typeBit', 'dataBits', 'orderCustom', 'dataCtx', 'reread'])}
const ctxRoot = () => ctxInterp;
const setCtxRoot = (holder) => { ctxInterp = holder; };
export { typeBit, dataBits, orderCustom, dataCtx, reread, ctxRoot, setCtxRoot };
`;
}

const file = path.join(__dirname, '..', 'lib', 'kernels', 'custom.mjs');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
