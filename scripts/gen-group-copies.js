'use strict';
// Writes the copies the 2.0 Validator's groups are built from, so a page that
// does not register a group carries none of its code, while lib/formats.js and
// lib/unique-items.js, which the 1.x engines, the code generator and the error
// runtime read (some as text), stay as they are:
//
//   lib/deq.js          _deq from lib/unique-items.js: enum and const equality,
//                       which every schema can need
//   lib/unique-dup.js   the rest of lib/unique-items.js: the uniqueItems
//                       duplicate search (the uniqueItems feature)
//   lib/formats-core.js lib/formats.js without the URI checks and the walk
//                       they load (the formats feature)
//   lib/uri-checks.js   the URI checks of lib/formats.js over lib/uri-core.js
//                       (the uri feature)
//
// Each piece is cut from its source by exact text, and the cut throws if the
// text has changed. tests/test_group_copies_sync.js fails when a copy has
// drifted.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

const LIB = path.join(__dirname, '..', 'lib');
const read = (f) => fs.readFileSync(path.join(LIB, f), 'utf8');
const HEAD = (from) => `'use strict';\n// Generated by scripts/gen-group-copies.js from lib/${from}. Do not edit.\n\n`;
const once = (src, text, file) => {
  if (src.split(text).length !== 2) throw new Error(`gen-group-copies: lib/${file} no longer holds, once, ${JSON.stringify(text.slice(0, 80))}`);
  return src.replace(text, '');
};

const UQ_REST = ['_uqh', '_uq', '_uqp', 'allDistinct', 'duplicatePair'];

// The URI part of lib/formats.js: the walk it loads, and the four checks over it.
const URI_LINES = [
  "const _uriWalk = require('./uri-core').__ataUri(ipv6);\n",
  'function uri (s) { return URI_FAST.test(s) || _uriWalk(s, 1); }\n',
  'function uriReference (s) { return _uriWalk(s, 0); }\n',
  'function iri (s) { return URI_FAST.test(s) || _uriWalk(s, 3); }\n',
  'function iriReference (s) { return _uriWalk(s, 2); }\n',
];
const URI_ENTRIES = ['    uri,\n', "    'uri-reference': uriReference,\n", '    iri,\n', "    'iri-reference': iriReference,\n"];
const URI_EXPORTS = [' uri, uriReference, uriWalk: _uriWalk,', ' iri, iriReference,'];

function render () {
  const uq = read('unique-items.js');
  if (!/^var _uqpI = 0;$/m.test(uq)) throw new Error('gen-group-copies: lib/unique-items.js no longer declares _uqpI as before');
  const deq = HEAD('unique-items.js') + take('unique-items.js', ['_deq']) + '\n\nmodule.exports = { _deq };\n';
  const dup = HEAD('unique-items.js') + "const { _deq } = require('./deq');\n\n" + take('unique-items.js', ['_uqh', '_uq']) + '\n\nvar _uqpI = 0;\n' +
    take('unique-items.js', ['_uqp', 'allDistinct', 'duplicatePair']) + '\n\nmodule.exports = { ' + UQ_REST.join(', ') + ' };\n';

  let f = read('formats.js');
  for (const l of URI_LINES) f = once(f, l, 'formats.js');
  for (const l of URI_ENTRIES) f = once(f, l, 'formats.js');
  for (const l of URI_EXPORTS) f = once(f, l, 'formats.js');
  if (/uriReference|iriReference|_uriWalk|uri-core/.test(f.replace(/^[ \t]*\/\/[^\n]*\n/gm, ''))) throw new Error('gen-group-copies: lib/formats.js reads the URI checks somewhere else as well');
  const core = HEAD('formats.js') + f.replace(/^'use strict';\n/, '').replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n');
  const uri = HEAD('formats.js') + "const { ipv6, URI_FAST } = require('./formats-core');\n" + URI_LINES.join('') +
    "\nmodule.exports = { uri, 'uri-reference': uriReference, iri, 'iri-reference': iriReference };\n";
  return { 'deq.js': deq, 'unique-dup.js': dup, 'formats-core.js': core, 'uri-checks.js': uri };
}

if (require.main === module) for (const [f, s] of Object.entries(render())) fs.writeFileSync(path.join(LIB, f), s);
module.exports = { render, LIB };
