'use strict';
// Writes the copies the 2.0 Validator's groups are built from, so a page that
// does not register a group carries none of its code, while lib/formats.js and
// lib/unique-items.js, which the 1.x engines, the code generator and the error
// runtime read (some as text), stay as they are:
//
//   lib/deq.js          _deq from lib/unique-items.js: enum and const equality,
//                       which every schema can need
//   lib/unique-dup.js   the rest of lib/unique-items.js: the uniqueItems
//                       duplicate search (the uniqueItems feature)
//   lib/features/format<Name>.js
//                       one feature per built-in format name (formatDate for
//                       date, formatDateTime for date-time, ...): the check of
//                       lib/formats.js and the declarations no other name reads
//   lib/fmt/<last>.js   declarations of lib/formats.js two or more names read
//                       (pair, ipv6, the URI walk, URI_FAST, ...), one module
//                       per set of names that read them, so a page carries a
//                       declaration only where a name it registers reads it
//                       and no declaration is in two modules
//   lib/features/formats.js and lib/features/uri.js
//                       every name but the URI ones, and the four URI names,
//                       one module each as lib/formats-core.js and
//                       lib/uri-checks.js were, apart from the per-name ones
//                       (featuresFor() names one way or the other per set,
//                       by features/format-sizes.mjs)
//   features/format<Name>.d.ts
//
// Each piece is cut from its source by exact text or by top-level
// declaration, and the cut throws if the source has changed shape.
// tests/test_group_copies_sync.js fails when a copy has drifted.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

const LIB = path.join(__dirname, '..', 'lib');
const read = (f) => fs.readFileSync(path.join(LIB, f), 'utf8');
const HEAD = (from) => `'use strict';\n// Generated by scripts/gen-group-copies.js from lib/${from}. Do not edit.\n\n`;

const UQ_REST = ['_uqh', '_uq', '_uqp', 'allDistinct', 'duplicatePair'];

const URI_NAMES = ['uri', 'uri-reference', 'iri', 'iri-reference'];
// The export name of the feature that checks format `name`, as lib/groups.js
// derives it: date-time is formatDateTime.
const { featureOf } = require('../lib/groups.js');

// The top-level statements of lib/formats.js, comment lines dropped: each
// declaration with the `for` lines that fill it, by name, in source order.
function declarations (src) {
  const lines = src.replace(/^'use strict';\n/, '').replace(/^[ \t]*\/\/[^\n]*\n/gm, '').split('\n');
  const decls = []; let cur = null;
  for (const line of lines) {
    const m = /^(?:function ([\w$]+) ?\(|(?:const|let|var) ([\w$]+) =|(for )|(module\.exports))/.exec(line);
    if (m && m[4]) { cur = null; break; }
    if (m && m[3]) {
      if (cur === null || !line.includes(cur.name + '[')) throw new Error('gen-group-copies: lib/formats.js has a top-level loop that does not fill the declaration before it: ' + line);
      cur.text += '\n' + line; continue;
    }
    if (m) { cur = { name: m[1] || m[2], text: line }; decls.push(cur); continue; }
    if (line === '') continue;
    if (cur === null || !/^[ \t}]/.test(line)) throw new Error('gen-group-copies: lib/formats.js has a top-level line outside a declaration: ' + line);
    cur.text += '\n' + line;
  }
  return decls;
}

// Identifiers a text reads: not property names after a dot, not words in a
// string literal or a trailing comment. One read too many only moves a
// declaration to a shared part; one missed fails tests/test_group_copies_sync.js.
const idents = (text) => new Set(text.replace(/'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"/g, "''").replace(/; \/\/[^\n]*/g, ';').match(/(?<![.\w$])[A-Za-z_$][\w$]*/g));

function formatsCopies () {
  const decls = declarations(read('formats.js'));
  const byName = new Map(decls.map((d) => [d.name, d]));
  // The table formatChecks() returns: format name to the expression checking it.
  const fc = byName.get('formatChecks');
  if (!fc) throw new Error('gen-group-copies: lib/formats.js has no formatChecks');
  const body = /return _checks \|\| \(_checks = \{\n([^]*?)\n  \}\);/.exec(fc.text);
  if (body === null) throw new Error('gen-group-copies: formatChecks in lib/formats.js no longer returns one table');
  const table = new Map();
  for (const line of body[1].split('\n')) {
    const m = /^    (?:'([\w-]+)'|([\w$]+))(?:: (.*))?,$/.exec(line);
    if (m === null) throw new Error('gen-group-copies: formatChecks entry not read: ' + line);
    table.set(m[1] || m[2], m[3] || m[2]);
  }
  for (const n of ['_checks', 'formatChecks']) byName.delete(n);
  const deps = new Map();
  for (const [name, d] of byName) deps.set(name, [...idents(d.text)].filter((x) => x !== name && byName.has(x)));
  const reach = (roots) => {
    const out = new Set(); const st = [...roots];
    while (st.length) { const x = st.pop(); if (out.has(x)) continue; out.add(x); st.push(...deps.get(x)); }
    return out;
  };
  const names = [...table.keys()];
  const reached = new Map(names.map((n) => [n, reach([...idents(table.get(n))].filter((x) => byName.has(x)))]));
  // The names that read each declaration; one no name reads is left out.
  const users = new Map();
  for (const [n, set] of reached) for (const x of set) (users.get(x) || users.set(x, []).get(x)).push(n);
  // A module per set of readers: the feature itself for one reader, a shared
  // part for more.
  const home = new Map(); const parts = new Map();
  for (const d of decls) {
    const u = users.get(d.name);
    if (!u) continue;
    if (u.length === 1) { home.set(d.name, 'f:' + u[0]); continue; }
    const key = u.slice().sort().join(' ');
    if (!parts.has(key)) parts.set(key, { file: null, decls: [] });
    parts.get(key).decls.push(d.name);
  }
  // A part is named after its last declaration, the one the others are
  // usually there for (ipv6 after ipv4Range and IPV6_FULL).
  for (const p of parts.values()) {
    p.file = p.decls[p.decls.length - 1] + '.js';
    for (const x of p.decls) home.set(x, 'p:' + p.file);
  }
  // A module's text: the requires of what it reads from others (its
  // declarations' and `extra`), its declarations in source order, and `tail`.
  const exported = new Set();
  const moduleText = (own, prefix, tail, extra) => {
    const ownSet = new Set(own);
    const imports = new Map();
    const want = (y) => {
      const h = home.get(y);
      if (!h.startsWith('p:')) throw new Error('gen-group-copies: ' + y + ' is read by a module it does not belong to, and is not shared');
      exported.add(y);
      (imports.get(h.slice(2)) || imports.set(h.slice(2), new Set()).get(h.slice(2))).add(y);
    };
    for (const x of own) for (const y of deps.get(x)) if (!ownSet.has(y)) want(y);
    for (const y of extra) if (!ownSet.has(y)) want(y);
    let s = HEAD('formats.js');
    for (const [file, set] of [...imports].sort()) s += `const { ${[...set].join(', ')} } = require('${prefix}${file.replace(/\.js$/, '')}');\n`;
    if (imports.size && own.length) s += '\n';
    s += own.map((x) => byName.get(x).text.replace(/require\('\.\//g, "require('../")).join('\n') + (own.length ? '\n' : '');
    return (s + tail).replace(/\n{3,}/g, '\n\n');
  };
  const out = {};
  for (const n of names) {
    const own = decls.map((d) => d.name).filter((x) => home.get(x) === 'f:' + n);
    const f = featureOf(n);
    const key = /^[\w$]+$/.test(n) ? n : `'${n}'`;
    const expr = table.get(n);
    const check = key === expr ? key : `${key}: ${expr}`;
    const roots = [...idents(expr)].filter((x) => byName.has(x));
    // Registered under the name of the group that holds it, whose checks the
    // Validator merges (lib/validator-small.js), so a core needs no slot per
    // name.
    const g = URI_NAMES.includes(n) ? 'uri' : 'formats';
    out['features/' + f + '.js'] = moduleText(own, '../fmt/', `\nmodule.exports = { ${f}: Object.freeze({ name: '${g}', checks: { ${check} } }) };\n`, roots);
  }
  // Parts after the features: what they hand out is what the others read.
  const partOrder = [...parts.values()];
  const partTexts = partOrder.map(({ file, decls: own }) => [file, moduleText(own, './', '', [])]);
  for (const [file, text] of partTexts) {
    const own = parts.get([...parts.keys()].find((k) => parts.get(k).file === file)).decls;
    out['fmt/' + file] = text + `\nmodule.exports = { ${own.filter((x) => exported.has(x)).join(', ')} };\n`;
  }
  // The two groups as one module each, as lib/formats-core.js and
  // lib/uri-checks.js were: a page registering a group carries no module per
  // name. They share nothing with the per-name modules, and featuresFor()
  // (features/index.mjs) names either the groups or the names for a page's
  // set, never both, by lib/format-sizes.js.
  const entry = (n) => { const k = /^[\w$]+$/.test(n) ? n : `'${n}'`; return k === table.get(n) ? k : `${k}: ${table.get(n)}`; };
  const groupText = (list, extra, header) => {
    const roots = new Set(extra);
    for (const n of list) for (const x of idents(table.get(n))) if (byName.has(x)) roots.add(x);
    const keep = reach(roots);
    return HEAD('formats.js').replace('Do not edit.', 'Do not edit.\n' + header) +
      decls.map((d) => d.name).filter((x) => keep.has(x)).map((x) => byName.get(x).text.replace(/require\('\.\//g, "require('../")).join('\n') + '\n';
  };
  const nonUri = names.filter((n) => !URI_NAMES.includes(n));
  // The URI walk and fast path are what the uri group reads of it.
  out['features/formats.js'] = groupText(nonUri, ['ipv6', 'URI_FAST'], '// Every built-in format check but uri, uri-reference, iri and iri-reference,\n// in one module: Validator.use(formats). It also hands ipv6 and URI_FAST to\n// the uri group (lib/features/uri.js).') +
    `\nmodule.exports = { formats: Object.freeze({ name: 'formats', checks: { ${nonUri.map(entry).join(', ')} } }), ipv6, URI_FAST };\n`;
  {
    const roots = new Set(); for (const n of URI_NAMES) for (const x of idents(table.get(n))) if (byName.has(x)) roots.add(x);
    const keep = reach(roots); for (const x of reach(['ipv6', 'URI_FAST'])) keep.delete(x);
    out['features/uri.js'] = HEAD('formats.js').replace('Do not edit.', 'Do not edit.\n// The uri, uri-reference, iri and iri-reference checks in one module, over\n// the formats group\'s ipv6 and URI_FAST: Validator.use(uri).') +
      "const { ipv6, URI_FAST } = require('./formats.js');\n" +
      decls.map((d) => d.name).filter((x) => keep.has(x)).map((x) => byName.get(x).text.replace(/require\('\.\//g, "require('../")).join('\n') + '\n' +
      `\nmodule.exports = { uri: Object.freeze({ name: 'uri', checks: { ${URI_NAMES.map(entry).join(', ')} } }) };\n`;
  }
  for (const n of names) {
    const f = featureOf(n);
    out['../features/' + f + '.d.ts'] = `// Generated by scripts/gen-group-copies.js. Do not edit.\n// ata-validator/features/${f}: the ${n} format check alone.\nimport type { Feature } from './index.js';\nexport declare const ${f}: Feature<'${f}'>;\n`;
  }
  return { out, names, featureOf, users, home };
}

function render () {
  const uq = read('unique-items.js');
  if (!/^var _uqpI = 0;$/m.test(uq)) throw new Error('gen-group-copies: lib/unique-items.js no longer declares _uqpI as before');
  const deq = HEAD('unique-items.js') + take('unique-items.js', ['_deq']) + '\n\nmodule.exports = { _deq };\n';
  const dup = HEAD('unique-items.js') + "const { _deq } = require('./deq');\n\n" + take('unique-items.js', ['_uqh', '_uq']) + '\n\nvar _uqpI = 0;\n' +
    take('unique-items.js', ['_uqp', 'allDistinct', 'duplicatePair']) + '\n\nmodule.exports = { ' + UQ_REST.join(', ') + ' };\n';
  return { 'deq.js': deq, 'unique-dup.js': dup, ...formatsCopies().out };
}

if (require.main === module) for (const [f, s] of Object.entries(render())) { fs.mkdirSync(path.dirname(path.join(LIB, f)), { recursive: true }); fs.writeFileSync(path.join(LIB, f), s); }
module.exports = { render, LIB, formatsCopies, featureOf };
