'use strict';

// Bake `lib/safe-regex.js` into `lib/safe-regex-source.js` as a plain string
// export so the AOT path (`lib/aot.js`) can embed the engine into generated
// modules without reading from disk at runtime. The runtime read used to be
// the reason browser bundles broke on first AOT call (and the reason the
// default entry had to carry `__dirname`/`fs`/`path`).
//
// Run from `prepublishOnly` and from a sync test so the bundled string never
// drifts from the engine source.

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'lib', 'safe-regex.js'), 'utf8');

const out =
  "'use strict';\n\n" +
  "// Auto-generated by scripts/regen-safe-regex-source.js — do not edit.\n" +
  "// Mirrors `lib/safe-regex.js` verbatim so `lib/aot.js` can embed the engine\n" +
  "// into standalone output without a runtime `fs` read. Kept in sync by\n" +
  "// `tests/test_safe_regex_source_sync.js`.\n\n" +
  'module.exports = ' + JSON.stringify(src) + ';\n';

const outPath = path.join(root, 'lib', 'safe-regex-source.js');
const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
if (prev === out) {
  console.log('lib/safe-regex-source.js: up to date');
} else {
  fs.writeFileSync(outPath, out);
  console.log('lib/safe-regex-source.js: regenerated');
}
