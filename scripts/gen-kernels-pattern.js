'use strict';
// Writes lib/kernels/safe-re.mjs and lib/ir/pattern-deps.mjs, ES
// module copies made from the text of the files that define them: the
// linear-time engine of lib/safe-regex.js, which a module written by
// ata-validator/ir imports (as compileSafe from ata-validator/kernels) for a
// pattern the Validator gives that engine, and the interpreted engine's
// choice of engine (compilePattern in lib/interpreter-core.js), which the
// Validator's removeAdditional pass uses and so does the ir's. The writers
// read the code generator's choice from lib/pattern-choice.js itself. The
// kernels reach no CommonJS file (see scripts/gen-kernels-cjs.js), hence
// copies; the engine's copy leaves out its comment lines.
// tests/test_kernels_pattern_sync.js fails when a copy and its source differ.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

const lib = (f) => fs.readFileSync(path.join(__dirname, '..', 'lib', f), 'utf8');
const fail = (why) => { throw new Error('gen-kernels-pattern: ' + why); };
function line (src, start, what) {
  const a = src.indexOf('\n' + start);
  if (a < 0) fail(what + ' not found');
  return src.slice(a + 1, src.indexOf('\n', a + 1));
}

function renderSafe () {
  const engine = require('../lib/safe-regex.js').engineSource().replace(/^[ \t]*\/\/.*\n/gm, '');
  if (/\brequire\(|\bmodule\.exports\b/.test(engine)) fail('the engine of lib/safe-regex.js is not self-contained');
  return `// Generated by scripts/gen-kernels-pattern.js from lib/safe-regex.js. Do not edit.
${engine}
// Built on the first pattern, so a module that names none of these builds nothing.
let E = null
const engine = () => E === null ? (E = __ataSafeRegex()) : E
export const compileSafe = (src) => engine().compileSafe(src)
`;
}

function renderEngine () {
  const ic = lib('interpreter-core.js');
  return `// Generated by scripts/gen-kernels-pattern.js from lib/interpreter-core.js. Do not edit.
import choice from '../pattern-choice.js'
const { compileSafe } = choice
${line(ic, 'const PLAIN_ATOM = ', 'PLAIN_ATOM')}
${take('interpreter-core.js', ['uRe', 'compilePattern', 'plainLinear'])}

// The code generator's choice (lib/pattern-choice.js), asked only of a
// pattern plainLinear does not accept. One it accepts runs in linear time on
// the RegExp and the code generator gives it the RegExp too
// (tests/test_regex_plain_linear.js holds that), so its parse is skipped: a
// tenth of the time for most patterns of a form.
const useSafeEngine = (src) => !plainLinear(src) && choice.useSafeEngine(src)
const matcherFor = (src) => useSafeEngine(src) ? compileSafe(src) : new RegExp(src, choice.reFlags(src))
export { compilePattern, plainLinear, useSafeEngine, matcherFor }
`;
}

const OUT = [
  { file: 'safe-re.mjs', render: renderSafe },
  { file: '../ir/pattern-deps.mjs', render: renderEngine },
];
const file = (c) => path.join(__dirname, '..', 'lib', 'kernels', c.file);
if (require.main === module) for (const c of OUT) fs.writeFileSync(file(c), c.render());
module.exports = { OUT, file };
