'use strict';
// Writes lib/rejection-core.js: the rejection objects and the error ordering
// of lib/rejections.js, the lines between its rejection-core markers, without
// the enrichment (lib/enrich-error.js) and typo correlation (lib/correlate.js)
// that follow them. The 2.0 Validator (lib/validator-small.js) requires the
// copy, so a page that does not register the richErrors feature does not
// carry the enrichment. lib/rejections.js keeps the code inline because a
// module boundary costs the lite and Workers bundles bytes and a Node process
// a module load. tests/test_rejection_core_sync.js fails when the copy has
// drifted.
const fs = require('fs');
const path = require('path');

const BEGIN = '// ---- rejection-core: begin ----\n';
const END = '// ---- rejection-core: end ----\n';
// The one line that differs: lib/rejections.js correlates an enriched list
// itself; in the copy the enrichment carries that step as `enrich.related`.
const RELATED = '  if (enrich && cached.length > 1) attachRelated(cached);\n';
const RELATED_COPY = '  if (enrich && cached.length > 1 && enrich.related !== undefined) enrich.related(cached);\n';
const EXPORTS = ['RichRejection', 'presentErrors', 'needsOrdering', 'sortErrorsBySchemaOrder', 'stripOrdinal', '_setPositionsFor'];

// The rejection-core lines follow LazyRejection, which the 2.0 Validator
// does not use; the require they need is written ahead of them.
const REQUIRE = "const { ordinalFor: schemaOrdinal, rankFor: schemaRank } = require('./schema-order');\n";

function render () {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', 'rejections.js'), 'utf8');
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('lib/rejections.js has no rejection-core markers');
  if (!src.includes(REQUIRE)) throw new Error('lib/rejections.js no longer requires lib/schema-order.js as the copy does');
  let body = src.slice(a + BEGIN.length, b);
  if (body.split(RELATED).length !== 2) throw new Error('lib/rejections.js: the correlation line of presentErrors has changed; update scripts/gen-rejection-core.js');
  body = body.replace(RELATED, RELATED_COPY);
  if (/enrich-error|correlate'|attachRelated|_enrichLazy/.test(body.replace(/^[ \t]*\/\/[^\n]*\n/gm, ''))) throw new Error('the rejection-core lines of lib/rejections.js reach the enrichment');
  return "'use strict';\n// Generated by scripts/gen-rejection-core.js from lib/rejections.js. Do not edit.\n\n" + REQUIRE +
    // Whole-line comments stay in lib/rejections.js, where the code is read.
    body.replace(/^[ \t]*\/\/[^\n]*\n/gm, '').replace(/\n{3,}/g, '\n\n') + '\nmodule.exports = { ' + EXPORTS.join(', ') + ' };\n';
}

const file = path.join(__dirname, '..', 'lib', 'rejection-core.js');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
