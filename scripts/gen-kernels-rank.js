'use strict';
// Writes lib/kernels/rank.mjs: the functions of lib/schema-order.js that rank
// a schemaPath, as their text, for the modules ata-validator/ir writes. A
// bundle then carries those five functions and not the rest of the module
// (ordinals, documents registered by other validators). Those modules never
// register documents, so a reference to another document is not followed,
// as in the current engine without one registered.
// tests/test_kernels_rank_sync.js fails when the copy and the source differ.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

function render () {
  return `// Generated by scripts/gen-kernels-rank.js from lib/schema-order.js. Do not edit.
const _keyIndexCache = new WeakMap();
const _rankCache = new WeakMap();
const _documents = new WeakMap();
const CONFLICT = null;
const remoteTarget = () => null;
${take('schema-order.js', ['keyIndex', 'unescapePointerSegment', 'rankFor', 'computeRank', 'localTarget'])}
export { rankFor };
`;
}

const file = path.join(__dirname, '..', 'lib', 'kernels', 'rank.mjs');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
