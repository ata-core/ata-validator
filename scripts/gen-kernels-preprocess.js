'use strict';
// Writes lib/kernels/preprocess.mjs: the passes lib/validator-core.js runs
// before a check under coerceTypes and removeAdditional, and the reading of a
// schema through references they use, as their text. ata-validator/ir runs
// them as the current engine does without loading the validator core.
// tests/test_kernels_preprocess_sync.js fails when the copy and the source differ.
const fs = require('fs');
const path = require('path');
const { take } = require('../lib/aot-order.js');

const NAMES = ['buildCoercer', 'coercionFor', 'buildNodeCoercer', 'buildSingleCoercion', 'buildRemover', 'collectRemovals', 'resolveRefForPreprocess', 'resolveSchemaForPreprocess'];

function render () {
  return `// Generated by scripts/gen-kernels-preprocess.js from lib/validator-core.js. Do not edit.
const _hasOwn = Object.prototype.hasOwnProperty;
${take('validator-core.js', NAMES)}
export { buildCoercer, buildRemover, resolveSchemaForPreprocess };
`;
}

const file = path.join(__dirname, '..', 'lib', 'kernels', 'preprocess.mjs');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
