'use strict';

// Writes lib/metaschemas.js from the official meta-schemas as fetched
// (scripts/metaschemas-source.json, unmodified), each read by the rules of
// the dialect it declares, as a registered schema is (lib/draft7.js). The
// rewrite ran at load, in every bundle that carries the meta-schemas; it runs
// here once and the file holds its result. tests/test_metaschemas_generated.js
// fails when the file and this script disagree.
//
//   node scripts/gen-metaschemas.js           write the file
//   require('./gen-metaschemas').source()     its text

const fs = require('fs');
const path = require('path');
const d7 = require('../lib/draft7');

const OUT = path.join(__dirname, '../lib/metaschemas.js');

function documents() {
  const out = [];
  for (const [id, doc] of JSON.parse(fs.readFileSync(path.join(__dirname, 'metaschemas-source.json'), 'utf8'))) {
    const code = d7.draftCode(doc.$schema);
    const copy = JSON.parse(JSON.stringify(doc));
    if (code === 3) d7.normalizeDraft2019(copy, true);
    else if (code === 1 || code === 2 || code === 4) {
      d7.normalizeDraft7(copy, true, code !== 1, code === 4);
      d7.normalizeExclusiveBounds(copy);
      // draft-04 gives `exclusiveMaximum` and `exclusiveMinimum` a default of
      // false and requires `maximum` and `minimum` beside them: filled into a
      // schema being checked (useDefaults is on unless turned off), the two
      // defaults made every schema without both bounds fail that rule. They
      // are left out; the other defaults are filled as before.
      if (code === 4) for (const k of ['exclusiveMaximum', 'exclusiveMinimum']) delete copy.properties[k].default;
    }
    out.push([id, copy]);
  }
  return out;
}

function source() {
  return `'use strict';

// Generated by scripts/gen-metaschemas.js. Do not edit.
//
// The official meta-schemas, vendored so a \`$ref\` to one of them resolves
// without a network. Draft 2020-12 is eight documents joined by $dynamicRef;
// draft-07, draft-06 and draft-04 are one each; 2019-09 is seven. Sources:
// https://json-schema.org/draft/2020-12/schema and
// http://json-schema.org/draft-07/schema, fetched 2026-08-23,
// http://json-schema.org/draft-06/schema and
// https://json-schema.org/draft/2019-09/schema, fetched 2026-10-10, and
// http://json-schema.org/draft-04/schema, fetched 2026-10-14.
// The 2020-12 documents are as fetched. The others are held as the engines
// read them: each rewritten by the rules of its own dialect (lib/draft7.js),
// as a caller's schema of that dialect is. Kept as fetched they were read
// under 2020-12, and the draft-04 one accepted \`multipleOf: 0\` and
// \`exclusiveMaximum\` without \`maximum\`. The draft-04 document also loses the
// defaults of \`exclusiveMaximum\` and \`exclusiveMinimum\`, which contradict
// its own \`dependencies\` once filled.
// Keyed by $id; index.js also registers the http/https and trailing-# spellings.

const METASCHEMAS = new Map([
${documents().map(([id, doc]) => `  [${JSON.stringify(id)}, ${JSON.stringify(doc)}],`).join('\n')}
]);

module.exports = { METASCHEMAS };
`;
}

module.exports = { source, OUT };

if (require.main === module) fs.writeFileSync(OUT, source());
