'use strict';
// Writes lib/kernels/unique.mjs and lib/kernels/collapse.mjs: lib/unique-items.js
// and lib/branch-collapse.js as ES modules, from their text. Both files import
// nothing. A module written by ata-validator/ir imports its helpers from
// ata-validator/kernels; a CommonJS file reachable from there stays in a
// bundle whether or not a helper of it is used (Next.js with webpack kept
// lib/formats.js, lib/error-codes.js and four more beside a compiled form,
// 9.9 KB gzipped where the form needs 4.2), so the kernels reach none.
// tests/test_kernels_cjs_sync.js fails when a copy and its source differ.
const fs = require('fs');
const path = require('path');

const COPIES = [
  { file: 'unique.mjs', from: 'unique-items.js', exports: ['_deq', 'duplicatePair'] },
  { file: 'collapse.mjs', from: 'branch-collapse.js', exports: ['__ataCollapse'] },
];

function render (c) {
  const src = fs.readFileSync(path.join(__dirname, '..', 'lib', c.from), 'utf8');
  const body = src.replace(/^'use strict';\n/, '').replace(/^module\.exports = \{[^\n]*\};\n?$/m, '');
  if (body === src || /\bmodule\.exports\b|\brequire\(/.test(body)) throw new Error('gen-kernels-cjs: ' + c.from + ' is not a self-contained CommonJS file');
  return `// Generated by scripts/gen-kernels-cjs.js from lib/${c.from}. Do not edit.\n${body.trimEnd()}\nexport { ${c.exports.join(', ')} };\n`;
}

const file = (c) => path.join(__dirname, '..', 'lib', 'kernels', c.file);
if (require.main === module) for (const c of COPIES) fs.writeFileSync(file(c), render(c));
module.exports = { COPIES, render, file };
