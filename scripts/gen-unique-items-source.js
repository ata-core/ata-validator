'use strict';
// Writes lib/unique-items-source.js: the uniqueItems helpers of
// lib/unique-items.js as the text the code generator puts into generated
// functions. Taken from the file at build time, not with String(fn) at run
// time: a bundler that renames identifiers renames the functions and the
// names they call each other by, and generated code calling `_uq` then threw
// "_uq is not defined" on every array. tests/test_unique_items_source_sync.js
// fails when this copy and the functions differ.
const fs = require('fs');
const path = require('path');
const u = require('../lib/unique-items.js');

const compact = (fn) => String(fn).replace(/\n\s*\/\/[^\n]*/g, '').replace(/\n\s*/g, '\n');

function render () {
  const uq = compact(u._uqh) + compact(u._uqrank) + compact(u._uqkeys) + compact(u._uqcmp) + compact(u._uqsorted) + compact(u._uq);
  const uqp = 'var _uqpI=0;' + compact(u._uqp);
  return `'use strict';
// Generated by scripts/gen-unique-items-source.js from lib/unique-items.js. Do not edit.
module.exports = { uq: ${JSON.stringify(uq)}, uqp: ${JSON.stringify(uqp)} };
`;
}

const file = path.join(__dirname, '..', 'lib', 'unique-items-source.js');
if (require.main === module) fs.writeFileSync(file, render());
module.exports = { render, file };
