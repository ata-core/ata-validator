'use strict';

// Source of the error runtime that compact modules import (see
// lib/error-runtime-entry.js for what it does). It is put together from the
// library's own files when a build asks for it, so there is no second copy of
// the interpreter to keep in step: each file becomes a function in a small
// module table, and require() inside them resolves against that table. The
// interpreter comes without its plan compiler (lib/interpreter-core.js), which
// produces the same errors.
//
// The output is not minified. It goes through the application's bundler like
// the modules that import it.

const fs = require('fs');
const path = require('path');

const FILES = [
  'error-runtime-entry',
  'interpreter-core',
  'error-sort-rank',
  'schema-order',
  'branch-collapse',
  'safe-regex',
  'unique-items',
  'formats',
  // The URI walk formats.js loads; left out with formats (see OPTIONAL).
  'uri-core',
];
// The parts a build can leave out when none of its schemas needs them. The
// decision is made on the schemas the runtime walks (as embedded, see
// runtimeFeatures) and errs toward keeping a part: a key with that name
// anywhere, even inside an enum value, keeps it. A part left out is replaced
// by a stub that throws, which a schema without that keyword cannot reach.
const OPTIONAL = {
  formats: { keys: ['format'], stub: 'module.exports = {};' },
  'safe-regex': { keys: ['pattern', 'patternProperties'], stub: "module.exports = { compileSafe() { throw new Error('ata error runtime: built without the pattern engine'); } };" },
  'unique-items': { keys: ['uniqueItems', 'enum', 'const'], stub: "function no() { throw new Error('ata error runtime: built without deep equality'); }\nmodule.exports = { allDistinct: no, duplicatePair: no, _deq: no };" },
};

// Which optional parts these schemas need: { formats, 'safe-regex',
// 'unique-items' } as booleans.
function runtimeFeatures(schemas) {
  const keys = new Set();
  const seen = new Set();
  const walk = (n) => {
    if (n === null || typeof n !== 'object' || seen.has(n)) return;
    seen.add(n);
    if (Array.isArray(n)) { for (const x of n) walk(x); return; }
    for (const k of Object.keys(n)) { keys.add(k); walk(n[k]); }
  };
  for (const s of schemas) walk(s);
  const out = {};
  for (const [part, { keys: ks }] of Object.entries(OPTIONAL)) out[part] = ks.some((k) => keys.has(k));
  return out;
}

function codeTable() {
  const { byKw, byFmt } = require('./error-code-of');
  return { byKw, byFmt };
}

// Lines that hold nothing but a // comment are about half of these files.
// They go, unless the line sits inside a template literal (tracked by
// counting backticks on the lines before it) or the file is one whose
// templates carry such lines on purpose (formats.js builds code from them).
const KEEP_COMMENTS = new Set(['formats']);
function dropCommentLines(src, name) {
  if (KEEP_COMMENTS.has(name)) return src;
  const out = [];
  let inTemplate = false;
  for (const line of src.split('\n')) {
    if (!inTemplate && /^\s*\/\//.test(line)) continue;
    if (!inTemplate && line.trim() === '') continue;
    out.push(line);
    const ticks = (line.match(/`/g) || []).length;
    if (ticks % 2 === 1) inTemplate = !inTemplate;
  }
  return out.join('\n');
}

const _cache = new Map();

// The files a schema-mode runtime adds: the verdict comes from the
// interpreter too, with its plan compiler for schemas used often.
const SCHEMA_FILES = ['schema-runtime-entry', 'interpreter', 'plan-compiler'];

// features: from runtimeFeatures, or omitted for a runtime with every part.
// schemaMode: also carry the verdict (createValidator), for schema modules.
function errorRuntimeSource(format, version, features, schemaMode) {
  const want = (part) => !features || features[part] !== false;
  const key = (format === 'cjs' ? 'cjs' : 'esm') + ':' + Object.keys(OPTIONAL).map((p) => (want(p) ? '1' : '0')).join('') + (schemaMode ? ':schema' : '');
  const hit = _cache.get(key);
  if (hit !== undefined) return hit;
  const defs = [];
  for (const name of schemaMode ? FILES.concat(SCHEMA_FILES) : FILES) {
    // uri-core goes with formats: only formats.js requires it.
    const part = name === 'uri-core' ? 'formats' : name;
    const src = OPTIONAL[part] !== undefined && !want(part)
      ? (name === 'uri-core' ? 'module.exports = {};' : OPTIONAL[part].stub)
      : dropCommentLines(fs.readFileSync(path.join(__dirname, name + '.js'), 'utf8'), name);
    // The files' own require('./x') calls go to the table under another name:
    // a tool that reads the runtime without scope (knip, a lint rule) took a
    // local `require` for an import of a file that is not there.
    const own = src.replace(/\brequire\((['"])\.\//g, '__ataReq($1./');
    defs.push(`${JSON.stringify(name)}: function (module, exports, __ataReq) {\n${own}\n}`);
  }
  const { byKw, byFmt } = codeTable();
  const body = `// Auto-generated by ata-validator ${version}, do not edit.
// The error runtime shared by the compact modules of one build. It imports
// nothing. Re-run the build after upgrading ata.
'use strict';
const _ataDefs = {
${defs.join(',\n')}
};
const _ataCache = {};
function _ataRequire(spec) {
  const name = spec.replace(/^\\.\\//, '').replace(/\\.js$/, '');
  const hit = _ataCache[name];
  if (hit !== undefined) return hit.exports;
  const def = _ataDefs[name];
  if (def === undefined) throw new Error('ata error runtime: missing module ' + spec);
  const module = { exports: {} };
  _ataCache[name] = module;
  def(module, module.exports, _ataRequire);
  return module.exports;
}
const _ataKw = ${JSON.stringify(byKw)};
const _ataFmt = ${JSON.stringify(byFmt)};
function _ataCode(k, f) {
  if (k === 'format' && f) { const h = _ataFmt[f]; return h === undefined ? 'ATA3099' : h; }
  const h = _ataKw[k];
  return h === undefined ? null : h;
}
// The modules are evaluated on the first call, not when this file loads.
function createErrors(schema, options) { return _ataRequire('error-runtime-entry').createErrors(schema, _ataCode, options); }
function compileSafe(src) { return _ataRequire('safe-regex').compileSafe(src); }
function uriWalk(s, m) { return _ataRequire('formats').uriWalk(s, m); }
${schemaMode ? "function createValidator(schema, options) { return _ataRequire('schema-runtime-entry').createValidator(schema, _ataCode, options); }\n" : ''}
const ataVersion = ${JSON.stringify(version)};

// Warm-up, in a browser only: the runtime's code compiles on its first use,
// which a page would otherwise pay for on its first rejected document, about
// a millisecond. When the browser is idle, one small error list is built here
// instead, once, so the first real one finds the code compiled. Nothing it
// does reaches a caller.
const WARM_SCHEMA = { type: 'object', properties: { a: { type: 'string' }, b: { type: 'integer', minimum: 0 }, c: { anyOf: [{ type: 'string' }, { type: 'null' }] }, f: { type: 'string', format: 'email' } }, required: ['d'], additionalProperties: false };
function warm() { try { createErrors(WARM_SCHEMA, { flat: true })({ a: 1, b: -1, c: 2, f: 'x', e: 0 }); } catch (_) {} }
if (typeof requestIdleCallback === 'function') { try { requestIdleCallback(warm); } catch (_) {} }
// In Node the same happens once the event loop is first free after start-up,
// on a timer that does not keep the process alive: a script that exits at
// once never runs it, and a server has it done before its first request.
else if (typeof process === 'object' && process !== null && process.versions && process.versions.node && typeof setTimeout === 'function') { try { const t = setTimeout(warm, 0); if (t && typeof t.unref === 'function') t.unref(); } catch (_) {} }
`;
  const out = format === 'cjs'
    ? body + `module.exports = { createErrors, compileSafe, uriWalk, ${schemaMode ? 'createValidator, ' : ''}ataVersion };\n`
    : body + `export { createErrors, compileSafe, uriWalk, ${schemaMode ? 'createValidator, ' : ''}ataVersion };\n`;
  _cache.set(key, out);
  return out;
}

module.exports = { errorRuntimeSource, runtimeFeatures, codeTable };
